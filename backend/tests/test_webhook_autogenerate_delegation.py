"""
Tests for webhook delegating to autogenerate when no schedule exists.

This ensures that when calendar webhooks fire before the user opens the app,
user preferences (sections, layout settings, etc.) are preserved from previous days.
"""

import pytest
from unittest.mock import MagicMock, patch
from backend.services.schedule_service import ScheduleService


class TestWebhookAutogenerateDelegation:
    """Test suite for webhook → autogenerate delegation flow."""

    def setup_method(self):
        """Setup test fixtures."""
        # Initialize service (it gets its own collection from db_config)
        self.service = ScheduleService()
        # Mock the collection for testing
        self.mock_collection = MagicMock()
        self.service.schedules_collection = self.mock_collection

    def test_webhook_no_schedule_calls_autogenerate_with_preferences(self):
        """
        Test that webhook calls autogenerate when no schedule exists,
        preserving user preferences from previous day.
        """
        user_id = "test-user-123"
        date = "2025-10-04"
        calendar_tasks = [
            {
                "id": "cal-1",
                "text": "Team Meeting",
                "gcal_event_id": "gcal-123",
                "from_gcal": True,
                "start_time": "10:00",
                "end_time": "11:00"
            }
        ]

        # Mock: No existing schedule for Oct 4
        self.mock_collection.find_one.side_effect = [
            None,  # First call: no schedule exists
            # Subsequent calls will be for autogenerate's internal lookups
        ]

        # Mock autogenerate to return a schedule with preferences
        with patch.object(self.service, 'autogenerate_schedule') as mock_autogen:
            mock_autogen.return_value = (True, {
                "existed": False,
                "created": True,
                "sourceFound": True,
                "date": date,
                "schedule": [
                    # Sections from previous day
                    {"id": "s1", "text": "Morning", "is_section": True, "type": "section"},
                    {"id": "t1", "text": "Review emails", "section": "Morning"},
                    # Calendar event will be merged in recursive call
                ]
            })

            # Mock the recursive call to apply_calendar_webhook_update
            with patch.object(self.service, 'apply_calendar_webhook_update', wraps=self.service.apply_calendar_webhook_update) as mock_apply:
                # First call triggers autogenerate, second call is recursive
                mock_apply.side_effect = [
                    mock_apply.return_value,  # First call executes our code
                    (True, {"schedule": [], "date": date, "metadata": {}})  # Recursive call returns success
                ]

                # Execute webhook update
                success, result = self.service.apply_calendar_webhook_update(
                    user_id=user_id,
                    date=date,
                    calendar_tasks=calendar_tasks
                )

                # Verify autogenerate was called
                mock_autogen.assert_called_once_with(
                    user_id=user_id,
                    date=date,
                    max_days_back=30
                )

                # Verify recursive call happened
                assert mock_apply.call_count == 2

    def test_webhook_autogenerate_existed_triggers_recursive_merge(self):
        """
        Test edge case: autogenerate returns 'existed' (race condition).
        Should trigger recursive call to merge calendar events.
        """
        user_id = "test-user-123"
        date = "2025-10-04"
        calendar_tasks = [{"id": "cal-1", "text": "Event", "gcal_event_id": "g1", "from_gcal": True}]

        # Mock: No existing schedule initially
        self.mock_collection.find_one.return_value = None

        with patch.object(self.service, 'autogenerate_schedule') as mock_autogen:
            # Autogenerate returns 'existed' (schedule appeared between checks)
            mock_autogen.return_value = (True, {
                "existed": True,
                "created": False,
                "sourceFound": True,
                "date": date,
                "schedule": [{"id": "t1", "text": "Existing task"}]
            })

            with patch.object(self.service, 'apply_calendar_webhook_update', wraps=self.service.apply_calendar_webhook_update) as mock_apply:
                mock_apply.side_effect = [
                    mock_apply.return_value,  # First call
                    (True, {"schedule": [], "date": date, "metadata": {}})  # Recursive call
                ]

                success, result = self.service.apply_calendar_webhook_update(
                    user_id=user_id,
                    date=date,
                    calendar_tasks=calendar_tasks
                )

                # Verify recursive call happened for race condition
                assert mock_apply.call_count == 2

    def test_webhook_autogenerate_fails_falls_back_to_calendar_only(self):
        """
        Test fallback: when autogenerate fails (first-time user, no source),
        webhook creates calendar-only schedule (original behavior).
        """
        user_id = "test-user-123"
        date = "2025-10-04"
        calendar_tasks = [
            {
                "id": "cal-1",
                "text": "First Event",
                "gcal_event_id": "gcal-123",
                "from_gcal": True
            }
        ]

        # Mock: No existing schedule
        self.mock_collection.find_one.return_value = None

        # Mock autogenerate to fail (no source found, first-time user)
        with patch.object(self.service, 'autogenerate_schedule') as mock_autogen:
            mock_autogen.return_value = (True, {
                "existed": False,
                "created": False,
                "sourceFound": False,  # No source schedule found
                "date": date,
                "schedule": []
            })

            with patch.object(self.service, '_create_schedule_document') as mock_create:
                with patch.object(self.service, '_serialize_tasks_for_storage', return_value=[]):
                    with patch('backend.services.schedule_service.validate_schedule_document', return_value=(True, None)):
                        mock_create.return_value = {
                            "userId": user_id,
                            "date": date,
                            "schedule": [],
                            "inputs": {},
                            "metadata": {"source": "calendar_sync"}
                        }

                        success, result = self.service.apply_calendar_webhook_update(
                            user_id=user_id,
                            date=date,
                            calendar_tasks=calendar_tasks
                        )

                        # Verify fallback behavior: create_schedule_document was called
                        mock_create.assert_called_once()
                        # Verify insert was called (fallback creates schedule)
                        self.mock_collection.insert_one.assert_called_once()

    def test_webhook_with_existing_schedule_unchanged(self):
        """
        Test that existing schedule path is completely unchanged.
        This verifies we didn't break the update scenario.
        """
        user_id = "test-user-123"
        date = "2025-10-04"
        calendar_tasks = [
            {
                "id": "cal-new",
                "text": "New Event",
                "gcal_event_id": "gcal-new",
                "from_gcal": True
            }
        ]

        # Mock: Existing schedule with preferences
        existing_schedule = {
            "userId": user_id,
            "date": "2025-10-04T00:00:00",
            "schedule": [
                {"id": "s1", "text": "Morning", "is_section": True, "type": "section"},
                {"id": "t1", "text": "Existing task", "section": "Morning"}
            ],
            "inputs": {
                "layout_preference": {
                    "layout": "todolist-structured",
                    "subcategory": "day-sections"
                }
            },
            "metadata": {
                "source": "manual",
                "created_at": "2025-10-04T08:00:00"
            }
        }

        self.mock_collection.find_one.return_value = existing_schedule

        with patch.object(self.service, '_filter_non_calendar_tasks', return_value=[]):
            with patch.object(self.service, '_filter_calendar_tasks', return_value=[]):
                with patch.object(self.service, '_normalize_calendar_tasks', return_value=calendar_tasks):
                    with patch.object(self.service, '_upsert_calendar_tasks_by_id', return_value=calendar_tasks):
                        with patch.object(self.service, '_rebuild_tasks_preserving_calendar_positions', return_value=calendar_tasks):
                            with patch.object(self.service, '_serialize_tasks_for_storage', return_value=calendar_tasks):
                                with patch.object(self.service, 'autogenerate_schedule') as mock_autogen:
                                    success, result = self.service.apply_calendar_webhook_update(
                                        user_id=user_id,
                                        date=date,
                                        calendar_tasks=calendar_tasks
                                    )

                                    # Verify autogenerate was NEVER called (existing schedule path)
                                    mock_autogen.assert_not_called()

                                    # Verify update was called (not insert)
                                    self.mock_collection.update_one.assert_called_once()
                                    self.mock_collection.insert_one.assert_not_called()

